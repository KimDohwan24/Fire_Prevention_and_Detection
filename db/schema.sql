-- =====================================================
-- 파이어가드 (Fire Prevention and Detection)
-- PostgreSQL 구축 스크립트  |  ERD v4 기반, 테이블 9개
-- (report_log 는 ERD v4 에 없던 것 — 119 송수신 이력을 남기려고 추가했다)
-- (user_activity 도 ERD v4 에 없던 것 — 접속·로그아웃 이력을 남기려고 추가했다)
--
-- ⚠️ 이 파일은 DB 를 처음부터 만드는 용도다. 아래 DROP SCHEMA 가
--    fireguard 스키마를 통째로 지우므로 기존 데이터는 전부 사라진다.
--    이미 쓰고 있는 DB 를 최신 구조로 맞추려면 db/migrations/ 의 파일을 쓸 것.
--
-- 📦 PostGIS 3 이 필요하다 (최근접 소방서 탐색에 쓴다). 설치 방법은
--    back/docs/team-setup.html 참고. CREATE EXTENSION 에는 superuser 권한이 든다.
--
-- =====================================================

DROP SCHEMA IF EXISTS fireguard CASCADE;

-- =====================================================
-- 0. 공간 확장 — 반드시 public 에 설치한다
--
-- fireguard 스키마 안에 설치하면 위 DROP SCHEMA CASCADE 가 확장까지 지워버린다.
-- 그래서 확장은 지워지지 않는 public 에 두고, 함수는 public. 을 붙여 부른다.
--
-- ⚠️ 순서가 중요하다. DROP SCHEMA 를 **먼저** 하고 그 다음에 확장을 만든다.
--    반대로 하면, 확장이 이미 fireguard 안에 있는 DB 에서 IF NOT EXISTS 가
--    '있으니 통과'로 넘어간 뒤 DROP SCHEMA 가 그 확장을 지워버려서
--    아래 public.ST_MakePoint 호출이 전부 깨진다.
--    이 순서 덕에 확장이 어디에 있었든 실행 후에는 public 에 놓인다.
--
-- ※ PostGIS 는 재배치가 안 되는 확장이라 ALTER EXTENSION ... SET SCHEMA 로는
--    옮길 수 없다. 기존 DB 를 옮기는 방법은 db/migrations/ 쪽에 있다.
-- =====================================================
CREATE EXTENSION IF NOT EXISTS postgis SCHEMA public;

-- =====================================================
-- 0-1. 스키마
-- =====================================================
CREATE SCHEMA IF NOT EXISTS fireguard;

-- 이 세션 동안 스키마 이름을 생략할 수 있게 한다
-- (Query Tool 을 새로 열면 초기화되므로 다시 실행해야 한다)
SET search_path TO fireguard, public;


-- -----------------------------------------------------
-- 1. 관리자 계정                                  [F-01]
-- -----------------------------------------------------
-- user_pw 가 NULL 일 수 있다 — 소셜 로그인 계정은 비밀번호를 갖지 않는다.
-- 대신 CK_USERS_LOCAL_PW 로 "일반(LOCAL) 계정이면 비밀번호 필수"를 강제한다.
CREATE TABLE fireguard.users (
    user_no            bigint        GENERATED BY DEFAULT AS IDENTITY,
    user_id            varchar(50)   NOT NULL,
    user_pw            varchar(255)  NULL,
    user_name          varchar(50)   NULL,
    user_email         varchar(100)  NULL,
    user_phone         varchar(20)   NULL,
    user_role          varchar(20)   NULL,
    user_status        varchar(20)   NULL,
    user_gender        varchar(10)   NULL,
    user_address       varchar(255)  NULL,
    user_provider      varchar(20)   NOT NULL  DEFAULT 'LOCAL',
    user_provider_id   varchar(191)  NULL,
    user_token_valid_from timestamp  NULL,
    user_created_at    timestamp     NULL  DEFAULT now(),
    user_updated_at    timestamp     NULL,
    user_withdrawal_at timestamp     NULL
);


-- -----------------------------------------------------
-- 2. 연동 카메라                             [F-02 F-08]
-- 신고 기관 선정의 기준 좌표가 여기에 있다
-- -----------------------------------------------------
CREATE TABLE fireguard.cctv (
    cctv_no         bigint         GENERATED BY DEFAULT AS IDENTITY,
    user_no         bigint         NOT NULL,
    cctv_name       varchar(100)   NULL,
    cctv_location   varchar(255)   NULL,
    -- 좌표를 역지오코딩한 주소. 119 신고에 싣는 값이다.
    -- cctv_location 은 사람이 붙인 설치 위치 설명('본관 정문 앞')이거나 ITS 카메라
    -- 이름('[수도권제1순환선] 판교분기점')이라 소방 지령에 쓸 수 없다.
    -- CCTV 등록 시점에 한 번 채운다 — 신고 순간에 외부 API 를 부르면 그 지연이
    -- 그대로 119 전송 지연이 된다 (신고는 동기 경로다).
    cctv_address    varchar(255)   NULL,
    cctv_lat        numeric(10,7)  NULL,
    cctv_lng        numeric(10,7)  NULL,
    cctv_stream_url varchar(500)   NULL,
    cctv_width      integer        NULL,
    cctv_height     integer        NULL,
    cctv_status     varchar(20)    NULL,
    cctv_created_at timestamp      NULL  DEFAULT now(),
    -- 공간 질의용 좌표점. 위경도에서 자동 파생되는 생성 컬럼이라 앱이 채우지 않는다
    -- (원본과 어긋날 수가 없다). ST_MakePoint 는 경도·위도 순서임에 주의.
    cctv_geog       public.geography(Point,4326)
        GENERATED ALWAYS AS (
            public.ST_SetSRID(
                public.ST_MakePoint(cctv_lng::double precision,
                                    cctv_lat::double precision), 4326
            )::public.geography
        ) STORED
);


-- -----------------------------------------------------
-- 3. 화재 판정 결과                         [F-03 F-06]
-- -----------------------------------------------------
CREATE TABLE fireguard.fire_event (
    event_no                bigint        GENERATED BY DEFAULT AS IDENTITY,
    cctv_no                 bigint        NOT NULL,
    event_status            varchar(20)   NULL,
    event_class             varchar(20)   NULL,
    event_first_detected_at timestamp     NULL,
    event_detected_at       timestamp     NULL,
    event_detected_frames   integer       NULL,
    event_threshold_frames  integer       NULL,
    event_confidence        numeric(5,4)  NULL,
    event_is_test           boolean       NOT NULL  DEFAULT false,
    -- CCTV 실시간 수집과 업로드 영상 테스트를 같은 이벤트 테이블에서 구분한다.
    event_source_type       varchar(20)   NOT NULL  DEFAULT 'CCTV_LIVE',
    event_source_metadata   jsonb         NULL,
    -- 테스트 당시 CCTV 정보. 이후 CCTV 이름/주소가 바뀌어도 이력은 그대로 남는다.
    event_cctv_snapshot     jsonb         NULL,
    event_processed_frames  integer       NULL,
    event_first_detected_offset_sec numeric(12,3) NULL,
    event_confirmed_offset_sec      numeric(12,3) NULL,
    event_test_started_at   timestamp     NULL,
    event_test_finished_at  timestamp     NULL
);


-- -----------------------------------------------------
-- 4. 검출 프레임                              [F-02 F-06]
-- 프레임만 저장한다 — CLIP(영상 클립)과 media_type 컬럼은
