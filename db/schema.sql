CREATE INDEX IX_user_activity_01 ON fireguard.user_activity (user_no, activity_at DESC);

-- 공간 인덱스 — 최근접 탐색(`<->` KNN)이 이걸 탄다.
-- B-tree 로는 거리 정렬을 색인할 수 없어 GiST 를 쓴다.
CREATE INDEX IX_agency_geog    ON fireguard.agency USING GIST (agency_geog);

-- 출처 고유번호는 기관을 가리키는 열쇠다. 손으로 등록한 행(NULL)은 제외한다.
CREATE UNIQUE INDEX UX_agency_source_id ON fireguard.agency (agency_source_id)
    WHERE agency_source_id IS NOT NULL;
CREATE INDEX IX_cctv_geog      ON fireguard.cctv   USING GIST (cctv_geog);

-- 진행 중인 신고가 이벤트당 하나만 있도록 DB 에서 강제한다
-- PostgreSQL 부분 인덱스 (MySQL 에는 없는 기능)
-- ⚠️ 이 상태 집합은 services/report_service.py 의 ACTIVE_STATUSES 와 반드시 같아야
--    한다. 어긋나면 출동 중인 화재에 신고가 한 번 더 나가거나(집합이 좁으면),
--    INSERT 가 유니크 위반 23505 로 터진다(집합이 넓으면).
CREATE UNIQUE INDEX UX_report_119_active ON fireguard.report_119 (event_no)
    WHERE report_status IN ('SENDING', 'ACCEPTED', 'DISPATCHED');

-- 같은 소셜 계정이 두 번 들어오지 않게. 일반(LOCAL) 계정은 provider_id 가 NULL 이라
-- 이 인덱스의 대상이 아니다 — 그래서 부분 인덱스여야 한다 (NULL 이 여럿이어도 무방).
CREATE UNIQUE INDEX UQ_USERS_PROVIDER ON fireguard.users (user_provider, user_provider_id)
    WHERE user_provider_id IS NOT NULL;


