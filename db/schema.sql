    media_url         varchar(500)  NULL,
    media_detections  jsonb         NULL,
    media_confidence  numeric(5,4)  NULL,
    media_captured_at timestamp     NULL,
    media_is_primary  boolean       NOT NULL  DEFAULT false,
    media_is_first    boolean       NOT NULL  DEFAULT false,
    media_is_confirmation boolean   NOT NULL  DEFAULT false,
    media_frame_index bigint        NULL,
    media_source_offset_sec numeric(12,3) NULL
);


-- -----------------------------------------------------
-- 5. 관리자 알림                                  [F-04]
-- 승격 단계 폐기 — PUSH·SMS 두 채널 동시 발송.
-- alert_level 컬럼은 2026-08-10 삭제 (항상 1 이었음)
-- -----------------------------------------------------
CREATE TABLE fireguard.alert (
    alert_no           bigint       GENERATED BY DEFAULT AS IDENTITY,
    event_no           bigint       NOT NULL,
    user_no            bigint       NOT NULL,
    alert_channel      varchar(20)  NULL,
    alert_status       varchar(20)  NULL,
    alert_sent_at      timestamp    NULL,
    alert_deadline_at  timestamp    NULL,
    alert_responded_at timestamp    NULL
);


-- -----------------------------------------------------
-- 6. 소방서                                      [F-05]
-- 승계 우선순위는 컬럼으로 두지 않는다
-- CCTV 좌표에서의 거리로 매번 산정한다
-- agency_endpoint 는 가상 119 서버 주소가 들어간다
-- -----------------------------------------------------
CREATE TABLE fireguard.agency (
    agency_no       bigint         GENERATED BY DEFAULT AS IDENTITY,
    agency_name     varchar(100)   NULL,
    agency_lat      numeric(10,7)  NULL,
    agency_lng      numeric(10,7)  NULL,
    agency_endpoint varchar(255)   NULL,
    agency_is_active boolean       NOT NULL  DEFAULT true,
    -- 출처(생활안전지도 IF_0038)의 고유번호 objt_id. 손으로 등록한 행은 NULL.
    -- 같은 이름의 소방서가 전국에 여럿 있어(중부소방서 5곳 등) 이름으로는 기관을
    -- 가릴 수 없다 — 적재 스크립트는 이 값으로 기존 행을 찾는다.
    agency_source_id varchar(40)  NULL,
    agency_address  varchar(255)  NULL,
    agency_phone    varchar(30)   NULL,
    -- 최근접 소방서 탐색의 대상 좌표점 (cctv_geog 와 같은 방식의 생성 컬럼)
    agency_geog     public.geography(Point,4326)
        GENERATED ALWAYS AS (
            public.ST_SetSRID(
                public.ST_MakePoint(agency_lng::double precision,
                                    agency_lat::double precision), 4326
            )::public.geography
        ) STORED
);


-- -----------------------------------------------------
-- 7. 119 신고                               [F-05 F-09]
-- 이벤트 1건에 여러 행이 쌓인다 (승계 이력)
-- report_sequence      기관을 몇 번째로 바꿨나 (바깥 루프)
-- report_attempt_count 그 기관에 몇 번 쐈나 (안쪽 루프, 최대 4)
-- -----------------------------------------------------
CREATE TABLE fireguard.report_119 (
    report_no             bigint        GENERATED BY DEFAULT AS IDENTITY,
    event_no              bigint        NOT NULL,
    agency_no             bigint        NOT NULL,
    report_sequence       integer       NULL,
    report_external_id    varchar(50)   NULL,
    report_trigger_reason varchar(100)  NULL,
    report_status         varchar(20)   NULL,
    report_address        varchar(255)  NULL,
    report_distance_km    numeric(6,3)  NULL,
    report_attempt_count  integer       NULL  DEFAULT 0,
    reported_at           timestamp     NULL,
    report_accepted_at    timestamp     NULL,
    -- 소방서가 출동 통지를 보내온 시각과 그 원문.
    -- report_accepted_at(접수 확인)과 뜻이 다르다 — 접수는 '신고를 받았다',
    -- 출동은 '소방차가 나갔다'이다. 기관마다 보내는 키가 달라 원문을 그대로 둔다.
    report_dispatched_at  timestamp     NULL,
    report_dispatch       jsonb         NULL
);


-- -----------------------------------------------------
-- 8. 119 송수신 로그                          [F-05 N-04]
-- 전송 시도 1회에 1행. 무엇을 보냈고 무엇이 돌아왔는지 그대로 남긴다.
-- report_119 는 결과 요약(상태·시도횟수·접수번호)만 갖고 있어서
-- "언제 보냈고 왜 승계했나"를 사후에 따질 근거가 없었다.
-- 응답이 없어 재전송한 것과 거절당해 재전송한 것은 뜻이 다르다 — log_result 로 구분한다.
-- -----------------------------------------------------
CREATE TABLE fireguard.report_log (
    log_no          bigint        GENERATED BY DEFAULT AS IDENTITY,
    report_no       bigint        NOT NULL,
    log_attempt     integer       NOT NULL,
    log_endpoint    varchar(500)  NULL,
    log_request     jsonb         NULL,
    log_result      varchar(20)   NULL,
    log_http_status integer       NULL,
    log_response    jsonb         NULL,
    log_error       varchar(500)  NULL,
    log_elapsed_ms  integer       NULL,
    log_sent_at     timestamp     NULL
);


-- -----------------------------------------------------
-- 9. 사용자 활동이력                              [F-01]
-- 사용자 1명에 N행. 접속·로그아웃뿐 아니라 계정 변경과 관제 조치까지 남긴다.
-- 종류는 아래 '상태값 정의' 블록의 activity_type 참고.
--
-- activity_target_no 와 activity_detail 은 "무엇을 했는지"를 구분하려고 뒀다.
-- 종류만 있으면 화재 조치 이력이 전부 똑같이 보여서, 언제 어느 카메라 건이었는지
-- 답할 수가 없다. target 은 대상 행의 번호(event_no / user_no), detail 은
-- 화면에 그대로 띄울 한 줄 요약이다. 둘 다 없어도 되는 값이라 NULL 을 허용한다.
--
-- IP 와 User-Agent 는 의도적으로 넣지 않았다 — "언제 들어오고 나갔나"만
-- 보여주기로 한 결정이다. 나중에 필요해지면 컬럼을 더하면 되지만,
-- 그 시점의 기존 행은 전부 NULL 로 남는다는 점은 알고 있어야 한다.
--
-- 실패한 시도는 여기 쌓지 않는다. 실패는 침입 시도 기록이지 활동 이력이 아니고,
-- 섞이면 '이 사람이 무엇을 했나'를 읽을 수 없게 된다.
--
-- ⚠️ JWT 는 무상태라 서버가 로그아웃 시점을 스스로 알 수 없다. LOGOUT 행은
--    프론트가 POST /api/auth/logout 을 불러줘야만 쌓인다. 브라우저를 그냥
--    닫으면 남지 않는다 — 명시적 로그아웃만 기록되는 표다.
-- -----------------------------------------------------
CREATE TABLE fireguard.user_activity (
    activity_no        bigint       GENERATED BY DEFAULT AS IDENTITY,
    user_no            bigint       NOT NULL,
    activity_type      varchar(20)  NOT NULL,
    activity_target_no bigint       NULL,
    activity_detail    varchar(255) NULL,
    activity_at        timestamp    NOT NULL  DEFAULT now()
);


