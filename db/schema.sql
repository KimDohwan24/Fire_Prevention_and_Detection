-- =====================================================
-- 상태값 정의 (참고용, 코드에서 비교하는 값)
-- =====================================================
-- users.user_role          : ADMIN(관리자) VIEWER(조회전용)
-- users.user_status        : ACTIVE(정상) PENDING(관리자 승격 승인 대기)
--                            SUSPENDED(정지) WITHDRAWN(탈퇴)
--                            PENDING 은 권한만 기다리는 정상 계정이다 — 로그인·계정 찾기가 되고
--                            user_role 은 VIEWER 그대로다. 승인되면 ADMIN·ACTIVE 가 된다.
-- users.user_provider      : LOCAL(아이디/비밀번호) GOOGLE KAKAO NAVER
--                            LOCAL 이 아니면 user_pw 가 NULL 이고 비밀번호 로그인이 막힌다.
--                            소셜 계정의 user_id 는 '{provider소문자}_{provider_id}' 를
--                            50자로 자른 합성값이다 (아이디 유니크 제약을 지키기 위한 것).
-- cctv.cctv_status         : ACTIVE(정상) INACTIVE(중지) ERROR(오류)
-- fire_event.event_status  : PENDING(누적중) CONFIRMED(확정) DISMISSED(기준미달)
-- fire_event.event_class   : FLAME(불꽃) SMOKE(연기) FLAME_SMOKE(둘다)
-- alert.alert_channel      : PUSH(앱알림) SMS(문자)
-- alert.alert_status       : SENT(발송) READ(확인) CANCELED(취소) NO_RESPONSE(무응답)
-- report_119.report_status : SENDING(전송중) ACCEPTED(접수확인)
--                            DISPATCHED(출동 통지 수신)
--                            NO_RESPONSE(무응답으로 승계) FAILED(전송실패)
--                            진행 중으로 보는 것은 앞의 셋이고, 이벤트당 1건만
--                            존재할 수 있다 (부분 유니크 인덱스 UX_report_119_active).
--   ⚠️ DISPATCHED 는 폐기했던 이름이 **다른 뜻으로** 부활한 것이다.
--      db/migrations/001 이 옛 DISPATCHED 를 ACCEPTED 로 개명했었다.
--        001 의 DISPATCHED = '119 서버가 신고를 받았다'  → 지금의 ACCEPTED
--        007 의 DISPATCHED = '소방차가 실제로 출동했다'  (119 가 콜백으로 알려준다)
--      001 만 읽고 '지웠던 걸 왜 되살렸나' 로 헷갈리지 않도록 여기 남긴다.
-- user_activity.activity_type : LOGIN(접속) LOGOUT(로그아웃)
--                            PASSWORD_CHANGED(비밀번호 변경) PROFILE_UPDATED(프로필 수정)
--                            FIRE_CONFIRMED(화재 확인) FIRE_DISMISSED(오탐 취소)
--                            target 이 붙는 것: PROFILE_UPDATED→user_no,
--                            FIRE_CONFIRMED/FIRE_DISMISSED→event_no
-- report_log.log_result    : ACCEPTED(2xx 접수확인) REJECTED(2xx 아닌 응답)
--                            TIMEOUT(응답 없음 — 상대는 접수했을 수 있다)
--                            ERROR(연결 실패 등 전송 자체가 안 됨)
--
-- media_detections 저장 형태 (좌표는 0~1 비율, YOLO 의 xywhn)
